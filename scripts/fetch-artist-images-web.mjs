import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ASSETS_DIR = join(root, 'assets', 'images', 'artists');
const UPLOADS_DIR = join(root, 'uploads', 'images');
const SOURCES_PATHS = [
  join(root, 'scripts', 'fest-artist-sources.json'),
  join(root, 'cms', 'data', 'fest-artist-sources.json'),
];
const GENERATED_TS = join(root, 'src', 'data', 'festArtistAssets.generated.ts');
const REPORT_PATH = join(root, 'scripts', 'fest-artist-web-fetch-report.json');
const CONTENT_PATH = join(root, 'cms', 'seed', 'content.json');

const PRESET = { width: 800, height: 800, quality: 82 };
const USER_AGENT = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36';

const args = new Set(process.argv.slice(2));
const dryRun = args.has('--dry-run');
const force = args.has('--force');
const limitArg = [...args].find((a) => a.startsWith('--limit='));
const limit = limitArg ? Number(limitArg.split('=')[1]) : undefined;
const artistArg = [...args].find((a) => a.startsWith('--artist='));
const onlyArtist = artistArg ? artistArg.slice('--artist='.length) : undefined;

function norm(s) {
  return s.toUpperCase().replace(/Ё/g, 'Е').replace(/[^A-ZА-Я0-9]/g, '');
}

function slugify(artist) {
  return norm(artist.split('/')[0]).toLowerCase().slice(0, 48) || 'artist';
}

function buildSearchQuery(artist) {
  const primary = artist.split('/')[0].trim();
  return `${primary} музыка`;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function searchDuckDuckGoImages(query) {
  const q = encodeURIComponent(query);
  const page = await fetch(`https://duckduckgo.com/?q=${q}&iax=images&ia=images`, {
    headers: { 'User-Agent': USER_AGENT },
  }).then((r) => r.text());

  const vqdMatch = page.match(/vqd=["']?([\d-]+)/);
  if (!vqdMatch) return [];

  const apiUrl =
    `https://duckduckgo.com/i.js?l=ru-ru&o=json&q=${q}` +
    `&vqd=${vqdMatch[1]}&f=,,,,,&p=1`;

  const data = await fetch(apiUrl, {
    headers: {
      'User-Agent': USER_AGENT,
      Referer: 'https://duckduckgo.com/',
    },
  }).then((r) => r.json());

  return data.results ?? [];
}

async function downloadFirstImage(results) {
  for (const result of results.slice(0, 8)) {
    const imageUrl = result.image;
    if (!imageUrl?.startsWith('http')) continue;

    try {
      const resp = await fetch(imageUrl, {
        headers: { 'User-Agent': USER_AGENT },
        redirect: 'follow',
      });
      if (!resp.ok) continue;

      const contentType = resp.headers.get('content-type') ?? '';
      if (!contentType.includes('image') && !/\.(jpe?g|png|webp|gif)(\?|$)/i.test(imageUrl)) {
        continue;
      }

      const buf = Buffer.from(await resp.arrayBuffer());
      if (buf.length < 1500) continue;

      await sharp(buf, { animated: false }).metadata();
      return { buf, imageUrl, title: result.title ?? '' };
    } catch {
      continue;
    }
  }

  return null;
}

async function optimizeAndSave(input, outPath) {
  const output = await sharp(input, { animated: false })
    .rotate()
    .resize(PRESET.width, PRESET.height, { fit: 'cover', position: 'centre' })
    .webp({ quality: PRESET.quality, effort: 4 })
    .toBuffer();
  await writeFile(outPath, output);
}

function loadSources() {
  const raw = readFileSync(SOURCES_PATHS[0], 'utf8');
  return JSON.parse(raw);
}

function saveSources(sources) {
  const json = JSON.stringify(sources, null, 2) + '\n';
  for (const path of SOURCES_PATHS) {
    writeFileSync(path, json);
  }
}

function regenerateAssetsTs(artists) {
  const entries = Object.entries(artists)
    .filter(([, url]) => url.startsWith('/api/uploads/images/'))
    .map(([artist, url]) => {
      const filename = url.split('/').pop();
      return { artist, assetFile: `../../assets/images/artists/${filename}` };
    })
    .sort((a, b) => a.artist.localeCompare(b.artist, 'ru'));

  const tsLines = [
    '// Generated by scripts — do not edit',
    '',
    'export const festArtistAssets: Record<string, number> = {',
    ...entries.map(({ artist, assetFile }) => `  ${JSON.stringify(artist)}: require('${assetFile}'),`),
    '};',
    '',
  ];
  writeFileSync(GENERATED_TS, tsLines.join('\n'));
}

async function main() {
  const content = JSON.parse(readFileSync(CONTENT_PATH, 'utf8'));
  const allArtists = [
    ...new Set([...content.schedule.map((s) => s.artist), ...content.autographs.map((a) => a.artist)]),
  ];

  const sources = loadSources();
  const existing = sources.artists ?? {};

  let targets = allArtists.filter((artist) => !existing[artist] || force);
  if (onlyArtist) {
    targets = targets.filter((artist) => artist === onlyArtist || norm(artist) === norm(onlyArtist));
    if (!targets.length) targets = [onlyArtist];
  }
  if (limit && limit > 0) targets = targets.slice(0, limit);

  console.log(`Artists to fetch: ${targets.length}${dryRun ? ' (dry-run)' : ''}`);

  mkdirSync(ASSETS_DIR, { recursive: true });
  mkdirSync(UPLOADS_DIR, { recursive: true });

  const usedSlugs = new Set(
    Object.values(existing)
      .map((url) => url.split('/').pop()?.replace(/\.webp$/, ''))
      .filter(Boolean),
  );

  const report = [];
  const updatedArtists = { ...existing };

  for (const artist of targets) {
    const query = buildSearchQuery(artist);
    console.log(`\n→ ${artist}`);
    console.log(`  query: ${query}`);

    if (dryRun) {
      const results = await searchDuckDuckGoImages(query);
      const preview = results[0];
      report.push({
        artist,
        query,
        status: 'dry-run',
        firstResult: preview?.image,
        title: preview?.title,
      });
      console.log(`  first: ${preview?.image ?? 'none'}`);
      await sleep(800);
      continue;
    }

    try {
      const results = await searchDuckDuckGoImages(query);
      if (!results.length) {
        report.push({ artist, query, status: 'no-results' });
        console.log('  no results');
        await sleep(800);
        continue;
      }

      const downloaded = await downloadFirstImage(results);
      if (!downloaded) {
        report.push({ artist, query, status: 'download-failed', tried: results.length });
        console.log('  download failed');
        await sleep(800);
        continue;
      }

      let slug = slugify(artist);
      let i = 2;
      while (usedSlugs.has(slug)) {
        slug = `${slugify(artist)}-${i++}`;
      }
      usedSlugs.add(slug);

      const assetFile = join(ASSETS_DIR, `${slug}.webp`);
      const uploadFile = join(UPLOADS_DIR, `${slug}.webp`);

      await optimizeAndSave(downloaded.buf, assetFile);
      await optimizeAndSave(downloaded.buf, uploadFile);

      const uploadUrl = `/api/uploads/images/${slug}.webp`;
      updatedArtists[artist] = uploadUrl;

      report.push({
        artist,
        query,
        status: 'ok',
        slug,
        sourceImage: downloaded.imageUrl,
        title: downloaded.title,
      });
      console.log(`  saved: ${slug}.webp`);
    } catch (error) {
      report.push({ artist, query, status: 'error', error: String(error) });
      console.log(`  error: ${error}`);
    }

    await sleep(1000);
  }

  if (!dryRun) {
    const aliasMap = {
      ГОРШЕНЕВ: 'ГОРШЕНЕВА',
      'RADIO ТАРО': 'RADIO TAPOK',
      RAVANNA: 'РАВАННА / RAVANNA',
      SELLOUT: 'СЕЛЛАУТ / SELLOUT',
      МЕЩЕРАА: 'МЕЩЕРА',
      'РАЗНЫЕ ЛЮДИ, МУХОМОРЫ': 'МУХОМОРЫ',
      'КОСТЯ КУЛЯСОВ': 'КОСТЯ КУЛЯСОВ. АНИМАЦИЯ',
      POLNALYUBVI: 'ПОЛНАЛЮБВИ / POLNALYUBVI',
      ПОЛНАЛЮБВИ: 'ПОЛНАЛЮБВИ / POLNALYUBVI',
      'ВИА ВОЛГА-ВОЛГА': 'ВИА «ВОЛГА-ВОЛГА»',
    };
    for (const [from, to] of Object.entries(aliasMap)) {
      if (updatedArtists[to] && !updatedArtists[from]) {
        updatedArtists[from] = updatedArtists[to];
      }
    }

    sources.source = 'web-search (duckduckgo)';
    sources.artists = updatedArtists;
    saveSources(sources);
    regenerateAssetsTs(updatedArtists);
    console.log(`\nUpdated ${SOURCES_PATHS.length} source files and ${GENERATED_TS}`);
  }

  writeFileSync(REPORT_PATH, JSON.stringify({ dryRun, targets: targets.length, report }, null, 2) + '\n');
  const ok = report.filter((r) => r.status === 'ok').length;
  console.log(`\nDone: ${ok}/${targets.length} saved. Report: ${REPORT_PATH}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
